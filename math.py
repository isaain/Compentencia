import math

print(math.gcd(24, 36))       # Output: 12
print(math.lcm(4, 6))         # Output: 12
print(math.factorial(5))      # Output: 120
print(math.isqrt(10))         # Output: 3
print(math.comb(5, 2))        # Output: 10


print(math.floor(4.9))        # Output: 4
print(math.ceil(4.1))         # Output: 5
print(pow(2, 10, 5))          # Output: 4 (2^10 % 5)


minimo = math.inf
minimo = min(minimo, 42)      # Output: 42

